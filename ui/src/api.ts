import { createClient, type SchemaSource } from "@kingsleyweb/bun-client";
import {
  ConversationParamsDto,
  ConversationQueryDto,
  ConversationResponseDto,
  ErrorResponseDto,
  HealthResponseDto,
  OutboxResponseDto,
  ResetParamsDto,
  ResetResponseDto,
  SendMessageResponseDto,
  SimulateBodyDto,
  SimulateResponseDto,
} from "../../src/dev/dev.dto";
import { manifest, type Routes } from "./api.gen";

/**
 * The server's own zod schemas, keyed like the generated route map, so the
 * client checks requests before sending them (the mobile-number refine
 * included) and responses as they arrive. A route added to the API shows up
 * in `Routes` (regenerated by `bun-client watch`), and `satisfies` flags a key
 * here that no longer exists.
 */
export const schemas = {
  "POST /dev/messages": {
    body: SimulateBodyDto,
    responses: {
      202: SendMessageResponseDto,
      400: ErrorResponseDto,
      429: ErrorResponseDto,
    },
  },
  "GET /dev/conversations/:waId": {
    params: ConversationParamsDto,
    query: ConversationQueryDto,
    responses: {
      200: ConversationResponseDto,
      400: ErrorResponseDto,
      429: ErrorResponseDto,
    },
  },
  "POST /dev/simulate": {
    body: SimulateBodyDto,
    responses: { 200: SimulateResponseDto, 400: ErrorResponseDto },
  },
  "DELETE /dev/users/:waId": {
    params: ResetParamsDto,
    responses: { 200: ResetResponseDto, 400: ErrorResponseDto },
  },
  "GET /dev/outbox": { responses: { 200: OutboxResponseDto } },
  "GET /health": { responses: { 200: HealthResponseDto } },
} satisfies SchemaSource<Routes>["schemas"];

/** Same-origin: the API serves the UI (from source in development, built otherwise). */
export const api = createClient<Routes>({
  baseUrl: window.location.origin,
  manifest,
  schemas: () => Promise.resolve({ schemas }),
  // Above the conversation read's longest wait (8 s).
  timeout: 15_000,
  retry: false,
});
